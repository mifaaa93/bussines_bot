def locale(code: str | None) -> str:
    if not code:
        return "en"
    value = code.lower().replace("_", "-")
    if value.startswith("uk"):
        return "uk"
    if value.startswith("ru"):
        return "ru"
    return "en"


def t(code: str | None, key: str, **kwargs: object) -> str:
    lang = code if code in _STRINGS else locale(code)
    text = _STRINGS[lang][key]
    return text.format(**kwargs) if kwargs else text
